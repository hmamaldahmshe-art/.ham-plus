'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const http=require('node:http'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {build}=require('../certificate-orders');
test('certificate requests enforce consent, identity and admin access',async t=>{
  const oldEnabled=process.env.HAM_CERT_ORDERS_ENABLED,oldStore=process.env.HAM_CERT_STORAGE_READY;
  t.after(()=>{if(oldEnabled===undefined)delete process.env.HAM_CERT_ORDERS_ENABLED;else process.env.HAM_CERT_ORDERS_ENABLED=oldEnabled;
    if(oldStore===undefined)delete process.env.HAM_CERT_STORAGE_READY;else process.env.HAM_CERT_STORAGE_READY=oldStore;});
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ham-orders-'));t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const service=build({dataDir:dir,getSession:req=>req.headers.cookie==='ham_sid=test'});
  const server=http.createServer((req,res)=>service.handle(req,res,new URL(req.url,'http://localhost').pathname).catch(e=>{res.writeHead(500);res.end(e.message);}));
  await new Promise(ok=>server.listen(0,'127.0.0.1',ok));t.after(()=>server.close());
  const base='http://127.0.0.1:'+server.address().port;
  const send=async (p,method='GET',payload=null,headers={})=>{const r=await fetch(base+p,{method,headers:payload?{'Content-Type':'application/json',...headers}:headers,body:payload?JSON.stringify(payload):undefined});return {status:r.status,body:await r.json()}};
  delete process.env.HAM_CERT_ORDERS_ENABLED;delete process.env.HAM_CERT_STORAGE_READY;
  let r=await send('/api/certificates/orders','POST',{name:'Test',deviceName:'iPhone',consent:true});assert.equal(r.status,503);
  process.env.HAM_CERT_ORDERS_ENABLED='true';process.env.HAM_CERT_STORAGE_READY='true';
  r=await send('/api/certificates/orders','POST',{name:'Test',deviceName:'iPhone',consent:false});assert.equal(r.status,400);
  r=await send('/api/certificates/orders','POST',{name:'Test',deviceName:'iPhone',consent:true});assert.equal(r.status,201);
  const {id,token}=r.body;assert.match(id,/^[a-f0-9-]{36}$/);
  assert.equal((await send('/api/admin/certificates/orders')).status,401);
  assert.equal((await send('/api/certificates/orders/'+id)).status,404);
  assert.equal((await send('/api/certificates/orders/'+id,'GET',null,{Authorization:'Bearer '+token})).status,200);
  const route='/api/certificates/orders/'+id+'/udid',auth={Authorization:'Bearer '+token};
  assert.equal((await send(route,'POST',{udid:'invalid'},auth)).status,400);
  assert.equal((await send(route,'POST',{udid:'00008030-001C195E1232002E'},auth)).status,200);
  r=await send('/api/admin/certificates/orders','GET',null,{cookie:'ham_sid=test'});
  assert.equal(r.body.orders.length,1);assert.equal(r.body.orders[0].source,'manual-unverified');
  r=await send('/api/admin/certificates/orders/'+id,'PUT',{status:'processing'},{cookie:'ham_sid=test'});
  assert.equal(r.status,200);
  r=await send('/api/certificates/orders/'+id,'GET',null,auth);assert.equal(r.body.status,'processing');
});
